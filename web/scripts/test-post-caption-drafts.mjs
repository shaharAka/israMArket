import assert from "node:assert/strict";
import fs from "node:fs";
import vm from "node:vm";
import ts from "typescript";
const source = fs.readFileSync(new URL("../lib/postCaptionDraft.ts", import.meta.url), "utf8");
const compiled = ts.transpileModule(source, {compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const rows = new Map();
const storage = {getItem:k=>rows.get(k)??null,setItem(k,v){rows.set(k,v);Object.defineProperty(this,k,{value:v,enumerable:true,configurable:true});},removeItem(k){rows.delete(k);delete this[k];}};
const fresh = (sessionStorage=null)=>{const exports={};vm.runInNewContext(compiled,{exports,window:{localStorage:storage,sessionStorage},Date,Map,encodeURIComponent});return exports;};
let api=fresh();
const key=api.captionDraftKey("account:1",3,"post:he/א","instagram");
assert.equal(api.writeCaptionDraft(storage,key,"Saved caption","נוסח עם אימוג׳י 🌿"),true);
api=fresh(); // Reload loses module memory; the persisted draft must still return.
assert.equal(api.readCaptionDraft(storage,key,"Saved caption").text,"נוסח עם אימוג׳י 🌿");
for(const other of [api.captionDraftKey("account:2",3,"post:he/א","instagram"),api.captionDraftKey("demo:1",3,"post:he/א","instagram"),api.captionDraftKey("account:1",4,"post:he/א","instagram"),api.captionDraftKey("account:1",3,"post:he/א","facebook")])assert.equal(api.readCaptionDraft(storage,other,"Saved caption"),null);
const conflict=api.readCaptionDraft(storage,key,"Newer saved caption");
assert.equal(conflict.base,"Saved caption","a newer saved post does not erase or rebase the owner's local work");
const kept=api.resolveCaptionDraftConflict(conflict,"Newer saved caption","keep",123456);
assert.deepEqual({...kept},{version:1,base:"Newer saved caption",text:"נוסח עם אימוג׳י 🌿",updated:123456},"keeping local text explicitly rebases it to the version reviewed");
assert.equal(api.resolveCaptionDraftConflict(conflict,"Newer saved caption","reload"),null,"reloading explicitly discards local text");
assert.equal(api.readCaptionDraft(storage,key,"נוסח עם אימוג׳י 🌿"),null,"already-saved text no longer needs recovery");
assert.equal(rows.has(key),false);
api.writeCaptionDraft(storage,key,"Original","",1000000);
assert.equal(api.readCaptionDraft(storage,key,"Original",1000001).text,"","intentionally empty drafts are preserved");
assert.equal(api.readCaptionDraft(storage,key,"Original",1000000+8*24*60*60*1000),null,"old private draft text expires");
rows.set(key,"broken JSON");assert.equal(api.readCaptionDraft(storage,key,"Original"),null);
rows.set(key,JSON.stringify({version:1,text:17,base:"Original",updated:Date.now()}));assert.equal(api.readCaptionDraft(storage,key,"Original"),null);
const blocked={getItem(){throw Error("blocked");},setItem(){throw Error("full");},removeItem(){throw Error("blocked");}};
assert.equal(api.writeCaptionDraft(blocked,key,"Original","Keep this"),false,"a failed durable save is reported honestly");
assert.equal(api.readCaptionDraft(blocked,key,"Original").text,"Keep this","SPA navigation retains memory fallback");
api.forgetCaptionDraft(blocked,key);assert.equal(api.readCaptionDraft(blocked,key,"Original"),null);
api.writeCaptionDraft(storage,key,"Original","Unsaved");api.forgetCaptionDraft(storage,key);assert.equal(api.readCaptionDraft(storage,key,"Original"),null,"explicit discard removes recovery");
const quickKey=api.quickPostDraftKey("account:1",3);
const quick={text:"טיוטת פוסט 🌿",destination:"instagram",language:"ar",changedLanguage:true,requestId:"ref-1",pending:{client_ref:"ref-1",text:"טיוטת פוסט 🌿",destination:"instagram",content_language:"ar"}};
const retried=api.quickPostRequest(quick,()=>"should-not-be-used");
const editedWhileUncertain=api.quickPostRequest({...quick,text:"נוסח חדש"},()=>"should-not-be-used");
assert.equal(retried.requestId,"ref-1");
assert.equal(editedWhileUncertain.requestId,"ref-1");
assert.equal(editedWhileUncertain.pending.text,"טיוטת פוסט 🌿","an uncertain retry reuses the original immutable request instead of changing content under one id");
assert.equal(api.quickPostRequest({...quick,pending:null,requestId:""},()=>"generated-id").requestId,"generated-id");
assert.equal(api.writeQuickPostDraft(storage,quickKey,quick,2000000),true);
api=fresh();
assert.equal(JSON.stringify(api.readQuickPostDraft(storage,quickKey,2000001)),JSON.stringify({...quick,version:1,updated:2000000}),"quick post survives a reload with its content language and request id");
for(const other of [api.quickPostDraftKey("account:2",3),api.quickPostDraftKey("demo:1",3),api.quickPostDraftKey("account:1",4),api.quickPostDraftKey("account:1")])assert.equal(api.readQuickPostDraft(storage,other,2000001),null,"quick post is isolated by owner and plan context");
assert.equal(api.readQuickPostDraft(storage,quickKey,2000000+8*24*60*60*1000),null,"expired quick post is discarded");
assert.equal(api.writeQuickPostDraft(blocked,quickKey,quick),false,"blocked storage is reported as memory-only for QuickPost too");
assert.equal(api.readQuickPostDraft(blocked,quickKey).pending.client_ref,"ref-1","QuickPost remains available in this mounted workspace when storage is blocked");
const sessionRows=new Map();
const session={getItem:k=>sessionRows.get(k)??null,setItem(k,v){sessionRows.set(k,v);Object.defineProperty(this,k,{value:v,enumerable:true,configurable:true});},removeItem(k){sessionRows.delete(k);delete this[k];}};
const redundant=api.fallbackDraftStorage(blocked,session);
assert.equal(api.writeQuickPostDraft(redundant,quickKey,quick),true,"session storage recovers blocked local storage before memory-only mode");
assert.equal(api.readQuickPostDraft(redundant,quickKey).pending.client_ref,"ref-1");
api=fresh(session);
api.clearCaptionDrafts();
assert.equal(sessionRows.size,0,"sign-out clears session fallback drafts too");
api.writeQuickPostDraft(storage,quickKey,quick,3000000);
api.clearCaptionDrafts();
assert.equal(rows.size,0,"sign-out clears both caption and quick post drafts from this device");
console.log("Post recovery: reload, owner/demo/month/channel isolation, explicit conflict choice, expiry, corruption, blocked storage, discard and sign-out passed");

// A full primary store may retain old bytes while the fallback accepts new work.
const quotaRows=new Map();
const quotaSessionRows=new Map();
let quotaFull=false;
const quotaStore={getItem:k=>quotaRows.get(k)??null,setItem:(k,v)=>{if(quotaFull)throw Error("quota");quotaRows.set(k,v);},removeItem:()=>{throw Error("read only");}};
const quotaSessionStore={getItem:k=>quotaSessionRows.get(k)??null,setItem:(k,v)=>quotaSessionRows.set(k,v),removeItem:k=>quotaSessionRows.delete(k)};
const resilient=api.fallbackDraftStorage(quotaStore,quotaSessionStore);
const sameMillisecond=Date.now();
api.writeCaptionDraft(resilient,key,"Original","Older copy",sameMillisecond);
quotaFull=true;
api.writeCaptionDraft(resilient,key,"Original","Latest copy",sameMillisecond);
api=fresh();
assert.equal(api.readCaptionDraft(resilient,key,"Original").text,"Latest copy","a stale read-only primary cannot hide newer fallback work, even within the same millisecond");
console.log("Storage quota recovery: newer fallback wins over an undeletable stale primary");
